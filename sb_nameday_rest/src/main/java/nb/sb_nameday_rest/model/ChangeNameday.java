package nb.sb_nameday_rest.model;

public class ChangeNameday {
    private String name;
    private String date;

    public ChangeNameday(String name, String date) {
        this.name = name;
        this.date = date;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDate() {
        return date;
    }

    public void setDate(String date) {
        this.date = date;
    }
}